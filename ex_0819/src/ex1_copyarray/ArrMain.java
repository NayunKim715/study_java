package ex1_copyarray;

public class ArrMain {
    public static void main(String[] args) {
        int[] array = {1, 2, 3, 4, 5}; 

        ArrSub as = new ArrSub();//메모리할당 받아둠
        as.param(array);

        System.out.println( "main : " + array[0] );
        //얕은복사 때문에 sub도 main도 둘다 100

        //array가 stack에 만들어짐
    }
}
/*
자바에서 변수가 선언되고 사용되는 위치에 따라 메모리에 저장되는 위치가 다르기 때문입니다.

- 스택(stack) 메모리: 메소드 내부에서 선언된 지역변수, 매개변수 등이 저장됩니다. 
  예를 들어 int[] array = {1,2,3,4,5}; 선언하면 이 array 참조 변수(주소를 저장하는 변수)는 스택에 저장됩니다.

- 힙(heap) 메모리: 실제 데이터(여기서는 int 값들로 이루어진 배열)나 new로 할당한 객체들은 모두 힙에 저장됩니다.
  즉, new int[]{1,2,3,4,5}로 생성된 배열 객체 자체는 힙에 저장됩니다.

왜 굳이 강조하냐면, 
기본 자료형(int, double, boolean 등)이 아닌 배열이나 객체들은 변수를 넘기거나 복사할 때 '주소값'이 스택에 복사되기 때문입니다.
그래서 파라미터로 넘길 때 배열이나 객체의 '주소'만 복사되어, 실제 힙에 있는 원본 데이터를 함께 '공유'하게 됩니다(얕은 복사).

따라서 sub 메소드에서 값을 바꾸면 힙에 있는 데이터가 바뀌고, main에서도 그 값을 볼 수 있습니다.
이런 '동작 원리'와 관련해서 스택과 힙의 구조를 알면, 값이 어떻게 바뀌는지, 어디가 바뀌는지 쉽게 이해가 되고, 
이해하지 못하면 복사를 했는데도 값이 같이 바뀌는 현상을 깨닫지 못하게 되니까 꼭 설명하는 것입니다.
*/